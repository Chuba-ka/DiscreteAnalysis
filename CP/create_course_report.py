def code(text, size=10):
    global y
    for line in text.splitlines():
        line_height = draw(line or ' ', LEFT, y, WIDTH - LEFT - RIGHT,
                           size=size, font='Liberation Mono', spacing=0, measure=True)
        if y + max(line_height, 12) > HEIGHT - BOTTOM:
            new_page()
        height = draw(line or ' ', LEFT, y, WIDTH - LEFT - RIGHT,
                      size=size, font='Liberation Mono', spacing=0)
        y += max(height, 12)
    y += 10



def table(headers, rows, widths, size=10):
    global y
    def row(cells, bold=False):
        global y
        heights = [draw(str(value), LEFT, y, width - 10, size=size,
                        bold=bold, spacing=1, measure=True)
                   for value, width in zip(cells, widths)]
        height = max(heights) + 9
        x = LEFT
        for value, width in zip(cells, widths):
            draw(str(value), x + 3, y + 3, width - 10, size=size,
                 bold=bold, spacing=1)
            x += width
        y += height
    row(headers, True)
    for cells in rows:
        height = max(draw(str(value), LEFT, y, width - 10, size=size,
                          spacing=1, measure=True)
                     for value, width in zip(cells, widths)) + 9
        if y + height > HEIGHT - BOTTOM:
            new_page()
            row(headers, True)
        row(cells)
    y += 10


